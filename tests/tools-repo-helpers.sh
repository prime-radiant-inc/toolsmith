# Helpers shared by the tests that install tools and commit to the tools
# repo (test-install.sh, test-move.sh). Source after lib.sh.

CATALOG_HEADER='# Tools catalog. Generated by toolsmith-repo; do not edit.'

# new_repo: fresh env with an initialised tools repo. Sets REPO and points
# TMPDIR (and so the staging area) inside the temp HOME, so staged files are
# cleaned up with it and their paths contain a space.
new_repo() {
    new_env
    TMPDIR="$T_HOME/tmp dir"
    mkdir -p "$TMPDIR"
    tr_run path
    REPO=$(kv repo)
}

# stage <name> [args]: run stage. Sets STAGED and BASE.
stage() {
    tr_run stage "$@"
    STAGED=$(kv staged)
    BASE=$(kv base)
}

# write_tool <file> <purpose>: write a shell tool with a toolsmith-v1 header.
write_tool() {
    printf '#!/bin/sh\n# toolsmith-v1: %s\necho %s\n' "$2" "$2" >"$1"
}

# install_new <name> <purpose> [args]: stage, write and install a tool.
install_new() {
    stage "$1" "${@:3}"
    write_tool "$STAGED" "$2"
    tr_run install "$STAGED" "$1" --base "$BASE" -m "add $1" "${@:3}"
}

head_rev() {
    t_git -C "$REPO" rev-parse HEAD
}

# changed_in_head [<path>...]: name-status of the files HEAD changed.
changed_in_head() {
    t_git -C "$REPO" diff-tree --no-commit-id --name-status -r HEAD -- "$@"
}

status_of() {
    t_git -C "$1" status --porcelain
}

exists() {
    [ -e "$1" ] && echo yes || echo no
}

# fail_commits: make every commit fail through a pre-commit hook in the
# test user's global config. allow_commits restores the plain config.
fail_commits() {
    local hooks="$T_HOME/hooks"
    mkdir -p "$hooks"
    printf '#!/bin/sh\necho "hook says no" >&2\nexit 1\n' >"$hooks/pre-commit"
    chmod +x "$hooks/pre-commit"
    printf '[core]\n\thooksPath = %s\n' "$hooks" >>"$T_GITCFG"
}

allow_commits() {
    printf '[user]\n\tname = Test\n\temail = test@example.com\n' >"$T_GITCFG"
}

# repo_state: HEAD, the tools repo's porcelain status, and every path in its
# work tree (outside .git) with each file's blob hash and executable bit.
repo_state() {
    t_git -C "$REPO" rev-parse HEAD
    status_of "$REPO"
    (
        cd -- "$REPO" || exit 1
        find . -path ./.git -prune -o -print | LC_ALL=C sort | while IFS= read -r path; do
            if [ -f "$path" ]; then
                printf '%s %s %s\n' "$path" "$(t_git hash-object -- "$path")" "$( [ -x "$path" ] && echo x || echo - )"
            else
                printf '%s dir\n' "$path"
            fi
        done
    )
}

# expect_rolled_back <desc> <state before>: assert the last install or move
# failed its commit and left the tools repo exactly as it was.
expect_rolled_back() {
    assert_rc "$1: failed commit exits 2" 2
    assert_contains "$1: git's stderr passed through" "hook says no" "$ERR"
    assert_contains "$1: hint names hooks and signing" "commit signing or hooks" "$ERR"
    assert_contains "$1: stderr says the change was rolled back" "rolled back" "$ERR"
    assert_eq "$1: repo state identical to before" "$2" "$(repo_state)"
    assert_eq "$1: lock released" no "$(exists "$REPO/.git/toolsmith.lock")"
}
