#!/usr/bin/env bash
# toolsmith-repo path and locate, global scope: finding and first-run
# initialisation of the tools repo.

. "$(dirname -- "$0")/lib.sh"

CATALOG_HEADER='# Tools catalog. Generated by toolsmith-repo; do not edit.'

# Physical path of the default tools repo location; it must already exist.
default_repo() {
    t_canonical "$T_HOME/.local/share/toolsmith/tools"
}

committed_files() {
    t_git -C "$1" ls-tree -r --name-only HEAD | tr '\n' ' '
}

commit_count() {
    t_git -C "$1" rev-list --count HEAD
}

notes() {
    printf '%s\n' "$OUT" | grep '^note='
}

# bin_without_git <dir>: a PATH directory holding bash and the utilities
# toolsmith-repo uses, but no git. Symlinks, because macOS kills copies of
# its signed system binaries.
bin_without_git() {
    local util
    mkdir -p "$1"
    for util in bash cat mkdir readlink; do
        ln -s "$(PATH=$T_DEFAULT_PATH command -v "$util")" "$1/$util"
    done
}

test_fresh_home() {
    new_env
    tr_run path
    assert_rc "path exits 0" 0
    local repo
    repo=$(default_repo)
    assert_eq "repo= is the canonical default path" "$repo" "$(kv repo)"
    assert_eq "global_catalog= is the repo's CATALOG.md" "$repo/CATALOG.md" "$(kv global_catalog)"
    assert_eq "repo is the toplevel of its own git repo" "$repo" "$(t_git -C "$repo" rev-parse --show-toplevel)"
    assert_eq "one commit" 1 "$(commit_count "$repo")"
    assert_eq "commit holds README and catalog" "CATALOG.md README.md " "$(committed_files "$repo")"
    assert_eq "catalog is the header line only" "$CATALOG_HEADER" "$(cat "$repo/CATALOG.md")"
    assert_contains "note says the repo was created" "note=created tools repo at $repo" "$OUT"
    assert_eq "commit uses the configured identity" "test@example.com" "$(t_git -C "$repo" log -1 --format=%ae)"
    assert_eq "no repo-local identity when one is configured" "" "$(t_git -C "$repo" config --local user.email)"
    assert_eq "stderr is empty" "" "$ERR"
}

test_dangling_relative_symlink() {
    new_env
    mkdir -p "$T_HOME/.local/share/toolsmith" "$T_HOME/x/y"
    ln -s ../../../target/tools "$T_HOME/.local/share/toolsmith/tools"
    T_CWD="$T_HOME/x/y"
    tr_run path
    assert_rc "path exits 0" 0
    assert_eq "target created relative to the symlink's directory" yes \
        "$( [ -d "$T_HOME/target/tools" ] && echo yes )"
    assert_eq "nothing created relative to the cwd" no \
        "$( [ -e "$(dirname -- "$T_HOME")/target" ] && echo yes || echo no )"
    assert_eq "symlink is still a symlink" yes \
        "$( [ -L "$T_HOME/.local/share/toolsmith/tools" ] && echo yes )"
    assert_eq "repo= is the canonical target" "$(t_canonical "$T_HOME/target/tools")" "$(kv repo)"
    assert_eq "target is a git repo with one commit" 1 "$(commit_count "$T_HOME/target/tools")"
}

test_existing_non_git_dir() {
    new_env
    mkdir -p "$T_HOME/.local/share/toolsmith/tools/bin"
    printf '#!/bin/sh\necho foo\n' >"$T_HOME/.local/share/toolsmith/tools/bin/foo"
    tr_run path
    assert_rc "path exits 0" 0
    local repo
    repo=$(default_repo)
    assert_eq "repo= is the existing dir" "$repo" "$(kv repo)"
    assert_eq "one commit" 1 "$(commit_count "$repo")"
    assert_eq "first commit holds existing files plus README and catalog" \
        "CATALOG.md README.md bin/foo " "$(committed_files "$repo")"
    assert_contains "note says the existing dir was initialised" "note=initialised existing directory $repo" "$OUT"
}

test_no_git_identity() {
    new_env
    T_GITCFG=/dev/null
    tr_run path
    assert_rc "path exits 0" 0
    local repo
    repo=$(default_repo)
    assert_eq "repo-local user.email" toolsmith@localhost "$(t_git -C "$repo" config user.email)"
    assert_eq "repo-local user.name" toolsmith "$(t_git -C "$repo" config user.name)"
    assert_eq "commit made as toolsmith" toolsmith@localhost "$(t_git -C "$repo" log -1 --format=%ae)"
    assert_contains "note mentions the repo-local identity" "repo-local git identity" "$(notes)"
}

test_second_run_is_quiet() {
    new_env
    tr_run path
    local first_repo=$(kv repo)
    tr_run path
    assert_rc "second path exits 0" 0
    assert_eq "same repo=" "$first_repo" "$(kv repo)"
    assert_eq "no new commit" 1 "$(commit_count "$first_repo")"
    assert_eq "no note=" "" "$(notes)"
    assert_eq "stderr is empty" "" "$ERR"
}

test_locate_creates_nothing() {
    new_env
    tr_run locate
    assert_rc "locate on a fresh home exits 0" 0
    local would_be
    would_be="$(t_canonical "$T_HOME")/.local/share/toolsmith/tools"
    assert_eq "repo= is the would-be path" "$would_be" "$(kv repo)"
    assert_eq "global_catalog= is the would-be catalog" "$would_be/CATALOG.md" "$(kv global_catalog)"
    assert_eq "~/.local not created" no "$( [ -e "$T_HOME/.local" ] && echo yes || echo no )"

    new_env
    mkdir -p "$T_HOME/.local/share/toolsmith"
    ln -s ../../../target/tools "$T_HOME/.local/share/toolsmith/tools"
    tr_run locate
    assert_rc "locate on a dangling symlink exits 0" 0
    would_be="$(t_canonical "$T_HOME")/target/tools"
    assert_eq "repo= is the symlink's would-be target" "$would_be" "$(kv repo)"
    assert_eq "global_catalog= is under the target" "$would_be/CATALOG.md" "$(kv global_catalog)"
    assert_eq "target not created" no "$( [ -e "$T_HOME/target" ] && echo yes || echo no )"
    assert_eq "symlink untouched" ../../../target/tools "$(readlink "$T_HOME/.local/share/toolsmith/tools")"

    new_env
    tr_run path
    local repo=$(kv repo)
    tr_run locate
    assert_rc "locate on an existing repo exits 0" 0
    assert_eq "locate agrees with path" "$repo" "$(kv repo)"
    assert_eq "locate prints no notes" "" "$(notes)"
}

test_git_missing() {
    new_env
    local tool_bin="$T_ROOT/bin without git"
    bin_without_git "$tool_bin"
    T_PATH="/nonexistent:$tool_bin"
    tr_run path
    assert_rc "path exits 6 without git" 6
    assert_contains "stderr says to install git" "Install git" "$ERR"
    assert_eq "nothing created" no "$( [ -e "$T_HOME/.local" ] && echo yes || echo no )"

    # The macOS Command Line Tools stub is a git on PATH that fails.
    new_env
    local stub_bin="$T_ROOT/bin with git stub"
    bin_without_git "$stub_bin"
    printf '#!/bin/sh\necho "xcrun: error: invalid active developer path" >&2\nexit 1\n' >"$stub_bin/git"
    chmod +x "$stub_bin/git"
    T_PATH="/nonexistent:$stub_bin"
    tr_run path
    assert_rc "path exits 6 with the git stub" 6
    assert_contains "stderr says to install git" "Install git" "$ERR"
    assert_eq "stub's own error is not passed through" "" \
        "$(printf '%s\n' "$ERR" | grep xcrun)"
    assert_eq "nothing created" no "$( [ -e "$T_HOME/.local" ] && echo yes || echo no )"
}

test_failed_first_commit_is_finished_later() {
    new_env
    local hooks="$T_ROOT/failing hooks"
    mkdir -p "$hooks"
    printf '#!/bin/sh\necho "pre-commit hook says no" >&2\nexit 1\n' >"$hooks/pre-commit"
    chmod +x "$hooks/pre-commit"
    printf '[core]\n\thooksPath = %s\n' "$hooks" >>"$T_GITCFG"
    tr_run path
    assert_rc "path exits 2 when the first commit fails" 2
    assert_contains "git's stderr is passed through" "pre-commit hook says no" "$ERR"
    assert_contains "stderr hints at signing or hooks config" "commit signing or hooks config" "$ERR"

    mv "$hooks/pre-commit" "$hooks/pre-commit.disabled"
    tr_run path
    assert_rc "rerun exits 0 once the hook is gone" 0
    local repo
    repo=$(default_repo)
    assert_eq "rerun finishes with one commit" 1 "$(commit_count "$repo")"
    assert_eq "commit holds README and catalog" "CATALOG.md README.md " "$(committed_files "$repo")"
    assert_contains "rerun notes the repo was created" "note=created tools repo at $repo" "$OUT"
}

