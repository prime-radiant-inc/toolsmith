# lib.sh's own cleanup, checked from child test processes.
test_lib_removes_its_work_dir() {
    local child="$T_ROOT/child cleanup.sh"
    printf '. "%s/lib.sh"\nprintf "%%s\\n" "$T_ROOT"\n' "$T_TESTS_DIR" >"$child"
    local child_root
    child_root=$("$BASH" "$child")
    assert_contains "child got a work dir" "/toolsmith-tests-$(id -u)/work." "$child_root"
    assert_eq "work dir removed when the child exits" no \
        "$( [ -e "$child_root" ] && echo yes || echo no )"
}

test_lib_cleanup_refuses_other_paths() {
    local victim="$T_ROOT/victim"
    mkdir -p "$victim"
    local child="$T_ROOT/child guard.sh"
    printf '. "%s/lib.sh"\nrmdir "$T_ROOT"\nT_ROOT=$1\n' "$T_TESTS_DIR" >"$child"
    local err
    err=$("$BASH" "$child" "$victim" 2>&1)
    assert_eq "dir outside the work-dir pattern survives" yes "$( [ -d "$victim" ] && echo yes )"
    assert_contains "cleanup says it refused" "refusing to remove $victim" "$err"
}

