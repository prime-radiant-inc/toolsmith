# Under a UTF-8 locale, a sed that is not run in the C locale rejects bytes
# that are not valid UTF-8. Purposes must pass through byte for byte either way.
test_non_utf8_bytes() {
    new_repo
    T_LC_ALL=C.UTF-8
    add_tool "$REPO" a-latin1 "$(printf '#!/bin/sh\n# toolsmith-v1: caf\351\n')"
    add_tool "$REPO" b-utf8 '#!/bin/sh
# toolsmith-v1: café ✓
'
    add_tool "$REPO" c-binary "$(printf '\177ELF\377\376\001\n\200\201\n')"
    commit_all
    tr_run catalog
    assert_rc "catalog exits 0" 0
    assert_eq "stderr is empty" "" "$ERR"
    assert_eq "Latin-1 purpose passes through byte for byte" \
        "$(printf -- '- %s/bin/a-latin1 -- caf\351' "$REPO")" "$(sed -n 2p "$REPO/CATALOG.md")"
    assert_eq "UTF-8 purpose passes through byte for byte" \
        "- $REPO/bin/b-utf8 -- café ✓" "$(sed -n 3p "$REPO/CATALOG.md")"
    assert_eq "binary with invalid bytes has no header" \
        "- $REPO/bin/c-binary -- (no toolsmith-v1 header)" "$(sed -n 4p "$REPO/CATALOG.md")"
}

