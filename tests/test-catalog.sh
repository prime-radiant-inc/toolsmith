test_project_scope() {
    new_repo
    local proj="$T_HOME/src/my app"
    mkdir -p "$proj"
    t_git -C "$proj" init -q
    tr_run locate --project "$proj"
    local pdir=$(kv project_dir)
    add_tool "$REPO" g '#!/bin/sh
# toolsmith-v1: Global G
'
    add_tool "$pdir" p '#!/bin/sh
# toolsmith-v1: Project P
'
    commit_all
    local global_before
    global_before=$(cat "$REPO/CATALOG.md")
    tr_run catalog --project "$proj"
    assert_rc "catalog --project exits 0" 0
    assert_eq "project catalog lists the project's tools only" "$CATALOG_HEADER
- $pdir/bin/p -- Project P" "$(cat "$pdir/CATALOG.md")"
    assert_eq "global catalog untouched" "$global_before" "$(cat "$REPO/CATALOG.md")"

    add_tool "$pdir" fresh '#!/bin/sh
# toolsmith-v1: Fresh
'
    tr_run catalog --project "$proj"
    assert_eq "project's uncommitted tool reported" "untracked=$pdir/bin/fresh" "$OUT"

    tr_run catalog
    assert_eq "global catalog ignores project tools" "$CATALOG_HEADER
- $REPO/bin/g -- Global G" "$(cat "$REPO/CATALOG.md")"
    assert_eq "global scope does not report project files" "" "$OUT"
}

