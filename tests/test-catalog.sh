test_untracked_reported() {
    new_repo
    add_tool "$REPO" old '#!/bin/sh
# toolsmith-v1: Old
'
    commit_all
    add_tool "$REPO" new '#!/bin/sh
# toolsmith-v1: New
'
    add_tool "$REPO" "with space" '#!/bin/sh
# toolsmith-v1: Spaced
'
    tr_run catalog
    assert_rc "catalog exits 0" 0
    assert_contains "uncommitted bin/new reported" "untracked=$REPO/bin/new" "$OUT"
    assert_contains "uncommitted name with a space reported unquoted" "untracked=$REPO/bin/with space" "$OUT"
    assert_eq "committed tool not reported" "" "$(printf '%s\n' "$OUT" | grep -F "/bin/old")"
    assert_eq "uncommitted tool is still catalogued" "- $REPO/bin/new -- New" "$(catalog_line new)"

    commit_all
    printf 'echo edited\n' >>"$REPO/bin/old"
    t_git -C "$REPO" add bin/old
    tr_run catalog
    assert_eq "staged-but-uncommitted edit reported" "untracked=$REPO/bin/old" "$OUT"

    t_git -C "$REPO" commit -q -m edit
    printf 'echo again\n' >>"$REPO/bin/old"
    tr_run catalog
    assert_eq "unstaged edit reported" "untracked=$REPO/bin/old" "$OUT"
}

# Under a global bin/ ignore, catalog still reports a hand-dropped stray as
# untracked (install would adopt it), but not a dotfile like .DS_Store.
test_untracked_reported_under_global_ignore() {
    new_repo
    ignore_bin_globally
    add_tool "$REPO" new '#!/bin/sh
# toolsmith-v1: New
'
    add_tool "$REPO" "with space" '#!/bin/sh
# toolsmith-v1: Spaced
'
    printf 'junk\n' >"$REPO/bin/.DS_Store"
    tr_run catalog
    assert_rc "catalog exits 0" 0
    assert_eq "ignored strays reported, .DS_Store not" \
        "$(printf 'untracked=%s/bin/new\nuntracked=%s/bin/with space' "$REPO" "$REPO")" \
        "$(printf '%s\n' "$OUT" | grep '^untracked=' | LC_ALL=C sort)"
    assert_eq "ignored stray catalogued" "- $REPO/bin/new -- New" "$(catalog_line new)"
    assert_eq ".DS_Store not catalogued" "" "$(grep -F ".DS_Store" "$REPO/CATALOG.md")"
}

test_catalog_does_not_commit() {
    new_repo
    add_tool "$REPO" a '#!/bin/sh
# toolsmith-v1: A
'
    commit_all
    local head
    head=$(t_git -C "$REPO" rev-parse HEAD)
    tr_run catalog
    assert_eq "no new commit" "$head" "$(t_git -C "$REPO" rev-parse HEAD)"
    assert_eq "CATALOG.md left modified in the work tree" " M CATALOG.md" \
        "$(t_git -C "$REPO" status --porcelain)"
}

test_first_run_creates_repo() {
