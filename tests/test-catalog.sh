#!/usr/bin/env bash
# toolsmith-repo catalog: generating CATALOG.md from tool headers, and
# reporting uncommitted tools.

. "$(dirname -- "$0")/lib.sh"

CATALOG_HEADER='# Tools catalog. Generated by toolsmith-repo; do not edit.'

# new_repo: fresh env with an initialised tools repo. Sets REPO.
new_repo() {
    new_env
    tr_run path
    REPO=$(kv repo)
}

# add_tool <scope-dir> <name> <content>: write an executable tool into
# <scope-dir>/bin.
add_tool() {
    mkdir -p "$1/bin"
    printf '%s' "$3" >"$1/bin/$2"
    chmod +x "$1/bin/$2"
}

commit_all() {
    t_git -C "$REPO" add -A
    t_git -C "$REPO" commit -q -m "add tools"
}

# catalog_line <name>: the catalog line for a global tool, from the catalog.
catalog_line() {
    grep -F -- "- $REPO/bin/$1 -- " "$REPO/CATALOG.md"
}

test_hash_header() {
    new_repo
    add_tool "$REPO" a '#!/bin/bash
# toolsmith-v1: Purpose A
echo a
'
    commit_all
    tr_run catalog
    assert_rc "catalog exits 0" 0
    assert_eq "bash tool listed with its purpose" "- $REPO/bin/a -- Purpose A" "$(catalog_line a)"
    assert_eq "stdout is empty" "" "$OUT"
    assert_eq "stderr is empty" "" "$ERR"
}

